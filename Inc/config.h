#ifndef NDWK_CONFIG_H
#define NDWK_CONFIG_H

/* ========================================================================== */
/*  1. よく調整するパラメータ (ターゲット環境に合わせて変更)                   */
/* ========================================================================== */

/**
 * @brief 推論に使用するCPUスレッド数
 * - PC (デスクトップ / ノート): 4
 * - マイコン / 小型ボード (Raspberry Pi Zero, Cortex-Aなど): 1 〜 2
 */
#define NDWK_NUM_THREADS            4

/**
 * @brief 速報字幕 (Partial) に渡す最大音声秒数
 * - PC: 6.0f (文頭から文章がリアルタイムに伸びていく)
 * - マイコン: 1.5f 〜 2.0f (CPU負荷を極小に抑え、処理落ちを防ぐ)
 */
#define NDWK_PARTIAL_WINDOW_SEC     6.0f

/**
 * @brief 速報字幕 (Partial) の更新間隔 (秒)
 * - 推奨値: 0.30f 〜 0.50f (人間の目の知覚にちょうど良い更新頻度)
 * - マイコンで負荷を落としたい場合は 0.50f に伸ばす
 */
#define NDWK_PARTIAL_INTERVAL_SEC   0.30f

/**
 * @brief 音声履歴バッファの保持秒数
 * - メモリ消費の目安: 16kHz float32 で 1秒あたり約 64 KB
 * - 10.0f で約 640 KB、5.0f で約 320 KB
 * - マイコンでRAMを数MB単位で節約したい場合は 5.0f に短縮可能
 */
#define NDWK_HISTORY_KEEP_SEC       10.0f


/* ========================================================================== */
/*  2. 精度・挙動のチューニング項目 (好みに応じて微調整)                       */
/* ========================================================================== */

/**
 * @brief 冒頭欠落を防ぐプリロール (前置) 秒数
 * - 標準推奨値: 1.0f (CERを劇的に改善する黄金値)
 * - 短くしすぎると「あしたの」の「あ」が削れるリスクがあります
 */
#define NDWK_PREROLL_SEC            1.0f

/**
 * @brief 発話終了とみなす無音時間 (秒)
 * - 標準値: 0.35f
 * - 小さくするほど話し終えてから確定までの体感速度が上がりますが、
 *   小さすぎると普通の息継ぎで文が細切れに分割されてしまいます
 */
#define NDWK_VAD_MIN_SILENCE_SEC    0.35f


/* ========================================================================== */
/*  3. 詳細設定 (注意: モデルの仕様に関わるため基本変更禁止)                */
/* ========================================================================== */

/**
 * @warning 【変更厳禁】サンプリングレート
 * すべての ONNX モデル（ReazonSpeech, Silero VAD, Whisper等）が
 * 16kHz 固定で学習されているため、変更すると認識が完全に壊れます。
 */
#define NDWK_SAMPLE_RATE            16000

/**
 * @warning 【変更厳禁】VAD 処理窓サイズ (サンプル数)
 * Silero VAD モデルの入力テンソル形状が 512 サンプル (32ms) 固定です。
 */
#define NDWK_VAD_WINDOW_SIZE        512

/**
 * @brief VAD の発話検知感度 (0.0 〜 1.0)
 * - 標準値: 0.5f
 * - 下げると小さな声も拾いますが、周囲の雑音・マイクノイズに過剰反応します。
 * - 上げるとハッキリ喋らないと検知しなくなります。
 */
#define NDWK_VAD_THRESHOLD          0.5f

/**
 * @brief 発話開始とみなす最小音声秒数
 * - 標準値: 0.25f (これ未満の極小ノイズやリップノイズを無視する)
 */
#define NDWK_VAD_MIN_SPEECH_SEC     0.25f

#endif // NDWK_CONFIG_H